param(
  [string]$Profile = 'desktop',
  [int]$WaitMinutes = 30
)

# Installs the current checkout into the DSH profile AFTER DSH has fully quit.
#
# `refresh-profile.ps1` must not run while DSH is open: the running app keeps the
# plugin tree locked (and AbSerialHost / DownloaderIpcBridge keep the downloader
# helper open), so pnpm would copy a half-written package. Running the install
# from inside the workbench terminal can never work — that terminal is a child of
# the DSH process it is trying to replace.
#
# This launcher writes a watcher script plus a sidecar env file, starts the
# watcher through WMI (so it is NOT a child of DSH and survives the app exiting),
# and returns immediately. The watcher polls until no DSH process is left, then
# runs the normal install and logs everything.

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not (Test-Path (Join-Path $repoRoot 'packages'))) {
  throw "not a dsh-workbay checkout: $repoRoot"
}

$pnpm = Get-Command pnpm.cmd -ErrorAction SilentlyContinue
if ($null -eq $pnpm) { $pnpm = Get-Command pnpm -ErrorAction SilentlyContinue }
if ($null -eq $pnpm) { throw 'pnpm is not on PATH; run "corepack enable" or open a new shell' }

$logPath = Join-Path $env:TEMP 'dsh-workbay-install.log'
$envPath = Join-Path $env:TEMP 'dsh-workbay-install-watcher.env'
$watcherPath = Join-Path $env:TEMP 'dsh-workbay-install-watcher.ps1'

$existing = Get-CimInstance Win32_Process -Filter "Name='powershell.exe'" -ErrorAction SilentlyContinue |
  Where-Object { $_.CommandLine -like "*$watcherPath*" }
if ($existing) {
  Write-Host 'a watcher is already waiting for DSH to exit' -ForegroundColor Yellow
  Write-Host "log: $logPath"
  return
}

# WMI's Win32_Process.Create cannot pass environment variables, so the watcher
# loads them from this sidecar as its first action.
$sidecarLines = @(
  ('$env:WBD_REPO = ''{0}''' -f $repoRoot),
  ('$env:WBD_PNPM = ''{0}''' -f $pnpm.Source),
  ('$env:WBD_LOG = ''{0}''' -f $logPath),
  ('$env:WBD_PROFILE = ''{0}''' -f $Profile),
  ('$env:WBD_WAIT_MINUTES = ''{0}''' -f $WaitMinutes)
) -join "`r`n"
[System.IO.File]::WriteAllText($envPath, $sidecarLines, (New-Object System.Text.UTF8Encoding($false)))

$watcher = @"
# Generated by scripts/install-on-exit.ps1 — safe to delete.
`$ErrorActionPreference = 'Continue'
. '$envPath'

`$log = `$env:WBD_LOG
`$deadline = (Get-Date).AddMinutes([int]`$env:WBD_WAIT_MINUTES)
`$names = @('DeepSeek Harness', 'AbSerialHost', 'DownloaderIpcBridge')

function Say([string]`$message) {
  `$line = '[{0}] {1}' -f (Get-Date -Format 'HH:mm:ss'), `$message
  Write-Host `$line
  Add-Content -LiteralPath `$log -Value `$line -Encoding UTF8
}

Say "waiting up to `$(`$env:WBD_WAIT_MINUTES) min for DSH to exit..."
while ((Get-Date) -lt `$deadline) {
  `$left = @(Get-Process -ErrorAction SilentlyContinue | Where-Object { `$_.ProcessName -in `$names })
  if (`$left.Count -eq 0) { break }
  Start-Sleep -Seconds 3
}
`$left = @(Get-Process -ErrorAction SilentlyContinue | Where-Object { `$_.ProcessName -in `$names })
if (`$left.Count -gt 0) {
  Say ('timed out; still running: ' + ((`$left | ForEach-Object { `$_.ProcessName } | Sort-Object -Unique) -join ', '))
  exit 1
}

Say 'DSH is closed; building chunks and installing the profile...'
Set-Location `$env:WBD_REPO
& `$env:WBD_PNPM run install:profile 2>&1 | ForEach-Object { Say `$_ }
if (`$LASTEXITCODE -ne 0) {
  Say "install failed with exit code `$LASTEXITCODE"
  exit `$LASTEXITCODE
}
Say 'done — start DSH again to load the new plugins.'
"@

[System.IO.File]::WriteAllText($watcherPath, $watcher, (New-Object System.Text.UTF8Encoding($true)))

$commandLine = 'powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}"' -f $watcherPath
$started = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{
  CommandLine      = $commandLine
  CurrentDirectory = $repoRoot
}
if ($started.ReturnValue -ne 0) {
  throw "could not start the watcher (Win32_Process.Create returned $($started.ReturnValue))"
}

Write-Host ''
Write-Host 'watcher started' -ForegroundColor Green
Write-Host '  1) quit DSH completely (tray icon too)' -ForegroundColor Yellow
Write-Host '  2) the install runs by itself as soon as DSH is gone' -ForegroundColor Yellow
Write-Host '  3) start DSH again to load the new plugins' -ForegroundColor Yellow
Write-Host ''
Write-Host "log:     $logPath"
Write-Host "watcher: $watcherPath"
