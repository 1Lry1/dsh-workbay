/**
 * Build the lazy client chunks.
 *
 * Client halves are single-file `window.__ModuleLoader__.load({ id, factory })`
 * bundles and cannot import npm packages, so heavy libraries (CodeMirror) are
 * bundled separately and fetched on first use. Each package may keep chunk
 * entries in `src/chunks/<name>.js`; this script bundles every entry to
 * `<package>/lib/chunks/<name>.js` in the format the client loader expects:
 *
 *   globalThis.__dshChunks__ = globalThis.__dshChunks__ || {}
 *   globalThis.__dshChunks__['<package-name>:<name>'] = (env) => { ...exports }
 *
 * `env.modules` carries the platform modules the host shell already loaded
 * (React and friends), so a chunk never bundles a second copy of React.
 *
 * Usage:  node scripts/build-chunks.mjs
 */
import { build } from 'esbuild'
import { readdirSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const packagesRoot = join(scriptsDir, '..', 'packages')

/** Platform modules a chunk may require; the client loader resolves them from the host bundle. */
const EXTERNALS = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']

function chunkTargets() {
  const targets = []
  let entries = []
  try {
    entries = readdirSync(packagesRoot, { withFileTypes: true })
  } catch {
    return targets
  }
  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    const dir = join(packagesRoot, entry.name)
    let files = []
    try {
      files = readdirSync(join(dir, 'src', 'chunks')).filter((name) => name.endsWith('.js'))
    } catch {
      continue
    }
    if (files.length === 0) continue
    let pkgName = entry.name
    try {
      pkgName = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name || entry.name
    } catch {
      /* keep the directory name */
    }
    targets.push({ dir, pkgName, files })
  }
  return targets
}

function wrapper(key, code) {
  // esbuild's CJS output references `require`, `module` and `exports`; the
  // wrapper provides them, so the chunk's own imports resolve to the host's
  // already-loaded React instead of a second copy.
  return [
    '/* generated by scripts/build-chunks.mjs - do not edit */',
    'globalThis.__dshChunks__ = globalThis.__dshChunks__ || {}',
    `globalThis.__dshChunks__[${JSON.stringify(key)}] = (env) => {`,
    '  const modules = (env && env.modules) || {}',
    '  const require = (spec) => {',
    '    if (!Object.prototype.hasOwnProperty.call(modules, spec)) {',
    `      throw new Error("chunk ${key} requires an unavailable module: " + spec)`,
    '    }',
    '    return modules[spec]',
    '  }',
    '  const module = { exports: {} }',
    '  const exports = module.exports',
    code,
    '  return module.exports',
    '}',
    '',
  ].join('\n')
}

async function main() {
  const targets = chunkTargets()
  if (targets.length === 0) {
    console.log('no chunks to build')
    return
  }
  let built = 0
  for (const { dir, pkgName, files } of targets) {
    for (const file of files) {
      const name = basename(file, '.js')
      const key = `${pkgName}:${name}`
      const result = await build({
        entryPoints: [join(dir, 'src', 'chunks', file)],
        bundle: true,
        write: false,
        format: 'cjs',
        platform: 'browser',
        target: ['chrome110'],
        external: EXTERNALS,
        legalComments: 'none',
        logLevel: 'warning',
        /* A chunk may `import css from 'some-package/style.css'`; esbuild then
           hands back the stylesheet as a string, which the chunk injects with a
           single <style> tag. Client halves cannot fetch a stylesheet of their
           own otherwise (no route of their own, no bundler). */
        loader: { '.css': 'text' },
      })
      const body = wrapper(key, result.outputFiles[0].text)
      const outDir = join(dir, 'lib', 'chunks')
      mkdirSync(outDir, { recursive: true })
      writeFileSync(join(outDir, `${name}.js`), body)
      console.log(`built ${key} -> packages/${basename(dir)}/lib/chunks/${name}.js (${Math.round(body.length / 1024)} KB)`)
      built += 1
    }
  }
  console.log(`done: ${built} chunk(s)`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
