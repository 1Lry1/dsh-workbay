/**
 * Tests for the lazy CodeMirror chunk `dsh-workbay-files:editor`.
 *
 * Run with:  node --test packages/files/tests/editor-chunk.test.mjs
 *
 * What is covered:
 *   1. `node scripts/build-chunks.mjs` emits lib/chunks/editor.js with the
 *      registry wrapper, and both the source and the bundle parse.
 *   2. The source module imports in plain Node without a DOM (CodeMirror only
 *      touches the DOM inside createEditor) and the extension -> language map
 *      is correct for every supported extension, filename form and unknown
 *      fallback. If a future CodeMirror release touches the DOM at import
 *      time, this degrades to asserting the built wrapper and an explicit skip.
 *   3. The built chunk evaluates in a sandbox-ish global, registers its factory
 *      under the exact key and returns the documented exports.
 *   4. `createEditor` rejects non-DOM containers immediately (in a child
 *      process with a hard timeout, so a hang would be caught instead of
 *      freezing the test runner).
 *
 * No real browser DOM is available in this environment, so mounting a live
 * editor is intentionally out of scope; the language resolver is pure and is
 * the only part that can be exercised headlessly.
 */
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import { existsSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, '..', '..', '..')
const SOURCE_PATH = join(REPO_ROOT, 'packages', 'files', 'src', 'chunks', 'editor.js')
const BUILT_PATH = join(REPO_ROOT, 'packages', 'files', 'lib', 'chunks', 'editor.js')
const REGISTRY_KEY = 'dsh-workbay-files:editor'

/** Every extension the chunk must understand (from docs/files-api.md §3). */
const SUPPORTED_EXTENSIONS = [
  'js',
  'mjs',
  'cjs',
  'ts',
  'tsx',
  'jsx',
  'json',
  'md',
  'markdown',
  'py',
  'go',
  'rust',
  'rs',
  'java',
  'c',
  'h',
  'cpp',
  'hpp',
  'cs',
  'html',
  'htm',
  'css',
  'xml',
  'yaml',
  'yml',
  'sql',
  'sh',
  'bash',
  'ps1',
]

/* ------------------------------------------------------------------------- *
 * 1. Build
 * ------------------------------------------------------------------------- */

test('build script emits the editor chunk under the registry key', { timeout: 180_000 }, (t) => {
  assert.ok(existsSync(SOURCE_PATH), `missing chunk source: ${SOURCE_PATH}`)

  let buildOutput = ''
  let buildError = null
  try {
    buildOutput = execFileSync(process.execPath, ['scripts/build-chunks.mjs'], {
      cwd: REPO_ROOT,
      encoding: 'utf8',
      timeout: 120_000,
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    })
  } catch (error) {
    buildError = error
    buildOutput = `${error.stdout || ''}\n${error.stderr || ''}`
  }

  assert.ok(
    existsSync(BUILT_PATH),
    `build did not produce ${BUILT_PATH}\n${buildOutput}`,
  )
  const builtStat = statSync(BUILT_PATH)
  assert.ok(builtStat.size > 0, 'built chunk is empty')

  if (buildError) {
    /* The same script also builds other packages' chunks. If a sibling chunk
     * is broken, keep testing against a bundle that is newer than our source
     * instead of hiding our own build failure. */
    const sourceStat = statSync(SOURCE_PATH)
    if (builtStat.mtimeMs + 1000 < sourceStat.mtimeMs) {
      throw new Error(`build failed and the existing bundle is older than the source\n${buildOutput}`)
    }
    t.diagnostic(`build script exited non-zero (possibly another package's chunk); reusing existing bundle\n${buildOutput}`)
  } else {
    assert.match(buildOutput, /dsh-workbay-files:editor/, 'build log should mention the editor chunk')
    assert.match(buildOutput, /done: \d+ chunk\(s\)/)
  }

  const built = readFileSync(BUILT_PATH, 'utf8')
  assert.ok(built.startsWith('/* generated by scripts/build-chunks.mjs'), 'bundle should carry the generated header')
  assert.ok(
    built.includes('globalThis.__dshChunks__ = globalThis.__dshChunks__ || {}'),
    'bundle should initialize the chunk registry',
  )
  assert.ok(
    built.includes(`globalThis.__dshChunks__[${JSON.stringify(REGISTRY_KEY)}] = (env) => {`),
    'bundle should register the editor factory under its registry key',
  )
  assert.ok(built.length > 100 * 1024, 'bundle should contain the CodeMirror payload')

  /* Both files must parse as scripts. `--check` on the built file also proves
   * the esbuild CJS body is valid standalone code (not ESM). */
  assert.doesNotThrow(() => {
    execFileSync(process.execPath, ['--check', SOURCE_PATH], { encoding: 'utf8', timeout: 30_000 })
  }, 'source chunk should pass node --check')
  assert.doesNotThrow(() => {
    execFileSync(process.execPath, ['--check', BUILT_PATH], { encoding: 'utf8', timeout: 30_000 })
  }, 'built chunk should pass node --check')
})

/* ------------------------------------------------------------------------- *
 * 2. Source module: no DOM needed at import time + language map
 * ------------------------------------------------------------------------- */

test('source chunk imports without a DOM and maps extensions to languages', async (t) => {
  let mod
  try {
    mod = await import(pathToFileURL(SOURCE_PATH).href)
  } catch (error) {
    /* Allowed fallback: assert the built wrapper instead and skip the
     * DOM-free language tests with an explicit reason. */
    assert.ok(existsSync(BUILT_PATH), 'no built chunk to fall back to')
    const built = readFileSync(BUILT_PATH, 'utf8')
    assert.ok(
      built.includes(`globalThis.__dshChunks__[${JSON.stringify(REGISTRY_KEY)}] = (env) => {`),
      'built wrapper should still register the factory',
    )
    t.skip(`source module needs browser-only CodeMirror internals at import time: ${error.message}`)
    return
  }

  assert.equal(typeof mod.createEditor, 'function', 'createEditor should be exported')
  assert.equal(typeof mod.languageFor, 'function', 'languageFor should be exported')
  assert.equal(mod.CHUNK_KEY, REGISTRY_KEY)

  for (const ext of SUPPORTED_EXTENSIONS) {
    const language = mod.languageFor(ext)
    assert.ok(language, `languageFor('${ext}') should return a language extension`)
  }

  /* Filename forms: case-insensitive, dot-prefixed extensions, POSIX and
   * Windows paths all normalize to the same map. */
  for (const filename of ['app.js', 'app.mjs', 'app.cjs', 'x.tsx', 'index.d.ts']) {
    const expected = filename.split('.').pop().toLowerCase()
    assert.ok(
      mod.languageFor(filename),
      `languageFor('${filename}') should resolve via the '.${expected}' extension`,
    )
  }
  assert.ok(mod.languageFor('.tsx'), 'a bare dot-prefixed extension should resolve')
  assert.ok(mod.languageFor('README.MD'), 'extensions should be matched case-insensitively')
  assert.ok(mod.languageFor('C:\\src\\main.go'), 'Windows paths should resolve')
  assert.ok(mod.languageFor('/home/user/lib.rs'), 'POSIX paths should resolve')

  /* Plain-text fallback for everything unknown. */
  for (const unknown of ['txt', 'log', 'unknown', 'lock', 'README', 'Makefile', '', '.', undefined, null, 42]) {
    assert.equal(mod.languageFor(unknown), null, `languageFor(${JSON.stringify(unknown)}) should be null`)
  }

  /* The resolver must be pure: it returns the same cached instance and must
   * not require a document. */
  assert.equal(mod.languageFor('a.ts'), mod.languageFor('b.ts'))
  assert.equal(typeof globalThis.document, 'undefined', 'the test host must not have a document')
})

/* ------------------------------------------------------------------------- *
 * 3. Built chunk: wrapper + exports
 * ------------------------------------------------------------------------- */

/**
 * Evaluate the built chunk in a sandbox-ish way: `new Function` shadows the
 * `globalThis` identifier with a plain object, so the generated wrapper
 * registers into that object instead of the real global. No browser is needed
 * because evaluating the CodeMirror modules does not touch the DOM.
 */
function loadBuiltChunk() {
  const code = readFileSync(BUILT_PATH, 'utf8')
  const sandboxGlobal = {}
  const factoryGetter = new Function(
    'globalThis',
    `${code}\n;return globalThis.__dshChunks__ && globalThis.__dshChunks__[${JSON.stringify(REGISTRY_KEY)}]`,
  )
  return { factory: factoryGetter(sandboxGlobal), registry: sandboxGlobal.__dshChunks__ }
}

test('built chunk registers the factory and exposes the documented API', { timeout: 120_000 }, (t) => {
  assert.ok(existsSync(BUILT_PATH), `missing built chunk: ${BUILT_PATH}`)

  let factory
  let registry
  try {
    ;({ factory, registry } = loadBuiltChunk())
  } catch (error) {
    /* Same fallback as above: assert only the wrapper text. */
    const built = readFileSync(BUILT_PATH, 'utf8')
    assert.ok(built.includes(`globalThis.__dshChunks__[${JSON.stringify(REGISTRY_KEY)}] = (env) => {`))
    t.skip(`built chunk needs browser-only CodeMirror internals at evaluation time: ${error.message}`)
    return
  }

  assert.equal(typeof factory, 'function', 'registry entry should be a factory function')
  assert.ok(registry, 'chunk should install globalThis.__dshChunks__')
  assert.deepEqual(Object.keys(registry), [REGISTRY_KEY])

  /* The editor chunk needs no platform modules (no React): an empty
   * env.modules must be enough. */
  const api = factory({ modules: {} })
  assert.equal(typeof api, 'object', 'factory should return the module exports')
  assert.equal(typeof api.createEditor, 'function', 'createEditor should be a function on the exports')
  assert.equal(typeof api.languageFor, 'function', 'languageFor should be a function on the exports')
  assert.equal(api.languageFor('component.tsx') !== null, true)
  assert.equal(api.languageFor('note.unknown-ext'), null)
  assert.equal(typeof api.CHUNK_KEY, 'string')
  assert.ok(Array.isArray(api.supportedExtensions), 'supportedExtensions should be exported for diagnostics')
  for (const ext of SUPPORTED_EXTENSIONS) {
    assert.ok(api.supportedExtensions.includes(ext), `supportedExtensions should include '${ext}'`)
  }
})

/* ------------------------------------------------------------------------- *
 * 4. createEditor fails fast without a real DOM (hard timeout, child process)
 * ------------------------------------------------------------------------- */

test('createEditor throws for non-DOM containers instead of hanging', { timeout: 30_000 }, (t) => {
  assert.ok(existsSync(BUILT_PATH), `missing built chunk: ${BUILT_PATH}`)

  /* A synchronous infinite hang would freeze the test runner itself, so probe
   * in a child process and kill it on timeout. */
  const probe = `
const { readFileSync } = require('node:fs')
const BUILT_PATH = ${JSON.stringify(BUILT_PATH)}
const REGISTRY_KEY = ${JSON.stringify(REGISTRY_KEY)}
let api
try {
  const code = readFileSync(BUILT_PATH, 'utf8')
  const sandboxGlobal = {}
  const factoryGetter = new Function('globalThis', code + '\\n;return globalThis.__dshChunks__ && globalThis.__dshChunks__[' + JSON.stringify(REGISTRY_KEY) + ']')
  const factory = factoryGetter(sandboxGlobal)
  api = factory({ modules: {} })
} catch (error) {
  console.log('EVAL_FAIL ' + (error && error.message))
  process.exit(0)
}
if (!api || typeof api.createEditor !== 'function') {
  console.log('NO_API')
  process.exit(2)
}
const failures = []
for (const [label, container] of [['null', null], ['undefined', undefined], ['plain object', {}], ['string', 'div']]) {
  let threw = false
  try {
    api.createEditor(container, { content: 'hello' })
  } catch (error) {
    threw = error instanceof TypeError || error instanceof Error
  }
  if (!threw) failures.push(label)
}
if (failures.length > 0) {
  console.log('NO_THROW ' + failures.join(','))
  process.exit(3)
}
console.log('OK')
process.exit(0)
`

  const result = spawnSync(process.execPath, ['-e', probe], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
    timeout: 20_000,
    windowsHide: true,
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  const stdout = (result.stdout || '').trim()
  const stderr = (result.stderr || '').trim()

  if (stdout.includes('EVAL_FAIL')) {
    t.skip(`built chunk cannot be evaluated headlessly: ${stdout}`)
    return
  }

  assert.equal(
    result.error && result.error.code,
    undefined,
    `child process did not finish within 20s (possible hang): ${JSON.stringify(result.error && result.error.message)}`,
  )
  assert.equal(result.status, 0, `createEditor guard failed: ${stdout || stderr}`)
  assert.equal(stdout, 'OK', `unexpected probe output: ${stdout || stderr}`)
})

/* ------------------------------------------------------------------------- *
 * 5. Source hygiene: browser-only chunk
 * ------------------------------------------------------------------------- */

test('chunk source stays browser-only and keeps the DSH contract', () => {
  const source = readFileSync(SOURCE_PATH, 'utf8')
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')

  assert.doesNotMatch(code, /from\s+['"]react/, 'chunk must not import React')
  assert.doesNotMatch(code, /from\s+['"]react-dom/, 'chunk must not import React DOM')
  assert.doesNotMatch(code, /from\s+['"]node:/, 'chunk must not import node: built-ins')
  assert.doesNotMatch(code, /from\s+['"](?:fs|path|os|child_process|url|util)['"]/, 'chunk must not import Node built-ins')
  assert.doesNotMatch(code, /\brequire\s*\(/, 'chunk must not use require()')
  assert.doesNotMatch(code, /\bimport\s*\(/, 'chunk must not use dynamic import()')

  /* Theme must be driven by the DSH alias variables so it follows the host. */
  for (const variable of [
    '--dsw-alias-bg-layer-1',
    '--dsw-alias-border-l2',
    '--dsw-alias-label-primary',
    '--dsw-alias-brand-primary',
    '--dsw-font-family-mono',
  ]) {
    assert.ok(source.includes(variable), `theme should reference ${variable}`)
  }

  /* Read-only mode uses both facets; line wrapping stays off (horizontal
   * scroll for code); Ctrl/Cmd+S is bound with preventDefault. */
  assert.match(source, /EditorState\.readOnly\.of\(true\)/, 'readOnly should set EditorState.readOnly')
  assert.match(source, /EditorView\.editable\.of\(false\)/, 'readOnly should set EditorView.editable(false)')
  assert.doesNotMatch(source, /EditorView\.lineWrapping/, 'line wrapping must stay off')
  assert.match(source, /key:\s*'Mod-s'/, 'Ctrl/Cmd+S should be bound')
  assert.match(source, /preventDefault:\s*true/, 'the save binding should prevent the browser default')
})
